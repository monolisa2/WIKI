1. 설치 페이지 접속 후 통합PC-보안 설치 클릭, 다운로드 후 설치 실행
2. 사용자 이름 입력 (예: 홍길동)
3. 사원 이메일 입력 (예: he@enliple.com)

### 5. 윈도우 PC 패스워드 설정
로컬 계정 · 로그인 암호 설정 기준

1. 시작 버튼 클릭 → 설정 열기 (단축키: Win + I)
2. 설정 → 계정 → 로그인 옵션으로 이동
3. 로그인 옵션에서 '암호' 항목 선택 (PIN(Windows Hello) · Microsoft 계정 로그인은 사용할 수 없습니다)
4. 새 암호 입력 → 확인 → 다음 → 완료 (이 암호는 보안장비를 통해 관리됩니다)

